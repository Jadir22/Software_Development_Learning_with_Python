# Basic Data Types and Variables in Python

name = "Rahim"          # str
age = 20                # int
cgpa = 3.75             # float
is_student = True       # bool

# Print values
print("Name:", name)
print("Age:", age)
print("CGPA:", cgpa)
print("Student:", is_student)

print()

# Check data types
print("Type of name:", type(name))
print("Type of age:", type(age))
print("Type of cgpa:", type(cgpa))
print("Type of is_student:", type(is_student))

print()

# Using variables in calculation
price = 100
quantity = 3
total = price * quantity

print("Price:", price)
print("Quantity:", quantity)
print("Total:", total)

print()

# int vs str
num1 = 10
num2 = 20

text1 = "10"
text2 = "20"

print("Integer addition:", num1 + num2)
print("String addition:", text1 + text2)